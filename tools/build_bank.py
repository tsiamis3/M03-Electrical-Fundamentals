"""Build data/bank.js from the per-lesson question files, and apply review decisions.

    python tools/build_bank.py                       # check every file and rebuild data/bank.js
    python tools/build_bank.py --review review.json  # first write the decisions from review.html into the lesson files

Source files (edit these, never bank.js):
    data/questions/L01.json, L02.json, ...   one list of questions per lesson
    data/questions/_misc.json                explanations shown for a named wrong answer (the "tags")

Question format (same as the M02 bank, plus lesson and status):
    {"id": "L01-shell3", "lesson": "L01", "topic": "3.01", "d": 1, "units": "SI",
     "q": {"en": ..., "el": ...}, "o": [{"en": ..., "el": ...}, x3], "a": 1,
     "tags": [tag or null for each option], "x": {"en": ..., "el": ...}, "status": "new"}
status: new (just written) -> approved (checked in class) | fix (needs a change, hidden) | retired (hidden for good)
"""
import argparse, hashlib, json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
QDIR = ROOT / "data" / "questions"
STATUSES = {"new", "approved", "fix", "retired"}


class BankBuilder:
    def __init__(self):
        self.lessons = json.loads((ROOT / "data" / "lessons.js").read_text(encoding="utf-8")
                                  .split("=", 1)[1].rstrip().rstrip(";"))
        self.misc = json.loads((QDIR / "_misc.json").read_text(encoding="utf-8"))
        self.files = sorted(p for p in QDIR.glob("L*.json"))
        self.errors = []

    def load(self, path):
        return json.loads(path.read_text(encoding="utf-8"))

    def apply_review(self, review_path):
        """review.json = {"<question id>": {"status": "approved"|"fix"|"retired", "note": "..."}}"""
        decisions = json.loads(pathlib.Path(review_path).read_text(encoding="utf-8"))
        changed = 0
        for f in self.files:
            qs = self.load(f)
            for q in qs:
                d = decisions.get(q["id"])
                if d and d.get("status") in STATUSES:
                    q["status"] = d["status"]
                    if d.get("note"):
                        q["note"] = d["note"]
                    elif "note" in q and d["status"] == "approved":
                        del q["note"]
                    changed += 1
            f.write_text(json.dumps(qs, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print(f"review: {changed} questions updated")

    def check(self, q, where):
        err = lambda m: self.errors.append(f"{where} {q.get('id', '?')}: {m}")
        for k in ("id", "lesson", "topic", "d", "q", "o", "a", "x"):
            if k not in q:
                err(f"missing '{k}'")
                return
        if q["topic"] not in self.lessons["topics"]:
            err(f"unknown topic {q['topic']}")
        if not 0 <= q["a"] < len(q["o"]):
            err("answer index out of range")
        if q.get("tags") and len(q["tags"]) != len(q["o"]):
            err("tags must have one entry per option")
        for t in q.get("tags") or []:
            if t and t not in self.misc:
                err(f"tag '{t}' is not in _misc.json")
        if q.get("status", "new") not in STATUSES:
            err(f"bad status {q.get('status')}")
        for part in [q["q"], q["x"], *q["o"]]:
            if not (part.get("en") and part.get("el")):
                err("every text needs both en and el")
                break

    def build(self):
        questions, seen = [], set()
        for f in self.files:
            for q in self.load(f):
                self.check(q, f.name)
                if q.get("id") in seen:
                    self.errors.append(f"{f.name}: duplicate id {q['id']}")
                seen.add(q.get("id"))
                q.setdefault("status", "new")
                questions.append(q)
        if self.errors:
            print("\n".join(self.errors))
            sys.exit(1)
        meta = {"count": len(questions), "topics": self.lessons["topics"],
                "exam": {"options": 3, "pass_mark": 0.75}}
        out = ROOT / "data" / "bank.js"
        out.write_text("// Generated by tools/build_bank.py from data/questions/*.json. Do not edit by hand.\nwindow.M3_BANK = " +
                       json.dumps({"meta": meta, "misc": self.misc, "questions": questions}, ensure_ascii=False) + ";\n",
                       encoding="utf-8")
        by = {}
        for q in questions:
            by.setdefault(q["lesson"], {}).setdefault(q["status"], 0)
            by[q["lesson"]][q["status"]] += 1
        print(f"wrote {out.relative_to(ROOT)}: {len(questions)} questions")
        for lid, c in sorted(by.items()):
            print(" ", lid, ", ".join(f"{k} {v}" for k, v in sorted(c.items())))


def stamp_pages():
    """Add ?v=<hash of the file> to every local .js/.css link in the pages, so browsers
    never mix a new page with old cached scripts (that left the Lessons page empty once)."""
    def ver(m):
        f = ROOT / m.group(2)
        v = hashlib.md5(f.read_bytes()).hexdigest()[:8] if f.exists() else "0"
        return f'{m.group(1)}{m.group(2)}?v={v}"'
    for page in ROOT.glob("*.html"):
        old = page.read_text(encoding="utf-8")
        new = re.sub(r'((?:src|href)=")((?:assets|data)/[^"?]+\.(?:js|css))(?:\?v=\w+)?"', ver, old)
        if new != old:
            page.write_text(new, encoding="utf-8")
    print("stamped script/css versions in the pages")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--review", help="review.json exported from review.html")
    args = ap.parse_args()
    b = BankBuilder()
    if args.review:
        b.apply_review(args.review)
    b.build()
    stamp_pages()
